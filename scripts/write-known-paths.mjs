/**
 * Write the route lists Vercel middleware uses:
 *   KNOWN_PATH_PATTERNS      every path that may continue (real pages and
 *                            redirect sources); anything else gets a 404.
 *   CANONICAL_PATH_PATTERNS  real pages in their canonical spelling; a
 *                            wrong-case address that matches exactly one
 *                            of them gets a 301 there instead of a 404.
 * Run from scripts/build-vercel-json.mjs so a new page in pages.config.js
 * or the SEO route list is allowed on the next build. The file is
 * committed too, because Vercel may bundle the middleware before the
 * build runs; api/_lib/known-paths.test.js fails when it is out of date.
 *
 *   node -e "import('./scripts/write-known-paths.mjs').then((m) => m.writeKnownPaths())"
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getCanonicalPathPatterns, getEdgeAllowPatterns } from './seo-routes.mjs';

const OUT = resolve(fileURLToPath(new URL('.', import.meta.url)), '../api/_lib/known-path-patterns.js');

export function writeKnownPaths() {
  const patterns = getEdgeAllowPatterns();
  const canonical = getCanonicalPathPatterns();
  const body = `// Generated by scripts/write-known-paths.mjs. Do not edit by hand.
// Regenerate with: node scripts/build-vercel-json.mjs
export const KNOWN_PATH_PATTERNS = ${JSON.stringify(patterns, null, 2)};

export const CANONICAL_PATH_PATTERNS = ${JSON.stringify(canonical, null, 2)};
`;
  writeFileSync(OUT, body, 'utf8');
  console.log(`[known-paths] wrote ${patterns.length} allow patterns, ${canonical.length} canonical`);
  return patterns;
}
