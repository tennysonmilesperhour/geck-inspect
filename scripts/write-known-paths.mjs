/**
 * Write the route allowlist that Vercel middleware uses to answer
 * unknown paths with HTTP 404. Run from scripts/build-vercel-json.mjs
 * so a new page in pages.config.js or the SEO route list is allowed
 * on the next build.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getEdgeAllowPatterns } from './seo-routes.mjs';

const OUT = resolve(fileURLToPath(new URL('.', import.meta.url)), '../api/_lib/known-path-patterns.js');

export function writeKnownPaths() {
  const patterns = getEdgeAllowPatterns();
  const body = `// Generated by scripts/write-known-paths.mjs. Do not edit by hand.
// Regenerate with: node scripts/build-vercel-json.mjs
export const KNOWN_PATH_PATTERNS = ${JSON.stringify(patterns, null, 2)};
`;
  writeFileSync(OUT, body, 'utf8');
  console.log(`[known-paths] wrote ${patterns.length} allow patterns`);
  return patterns;
}
