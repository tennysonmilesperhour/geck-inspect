#!/usr/bin/env node
/**
 * Builds the Weekly Gecko Notes catalog that send-email ships with.
 *
 *   pnpm build:weekly-notes
 *
 * Reads every content/weekly-notes/NNN-slug.md, checks each one against the
 * rules in scripts/lib/weekly-notes.mjs, adds any new slug to
 * content/weekly-notes/published-slugs.json (the append-only list that stops
 * a published slug being renamed or reused) and writes
 * supabase/functions/_shared/weekly-notes.generated.ts. While any note
 * breaks a rule, or a published slug has gone missing, it prints the
 * problems and writes nothing, so a broken note can never reach the
 * catalog.
 *
 * The output is deterministic (same notes in, same bytes out), so the test
 * in src/lib/__tests__/weeklyNotes.test.js can fail when the generated file
 * is stale. It is not chained into `pnpm build` on purpose: a build should
 * never rewrite a tracked file. The stale test is the gate.
 *
 * Sources (the repo lines behind each fact) stay in the note files for
 * reviewers; they are not shipped.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import {
  allProblems,
  GENERATED_FILE,
  GENERATED_FILE_REL,
  NOTES_DIR_REL,
  PUBLISHED_FILE,
  PUBLISHED_FILE_REL,
  publishedFileText,
  readPublished,
  readWeeklyNotes,
  withNewSlugs,
} from './lib/weekly-notes.mjs';

const HEADER = 'Generated by scripts/build-weekly-notes.mjs from content/weekly-notes. Do not edit by hand; run pnpm build:weekly-notes.';

const FIELDS = ['step', 'slug', 'subject', 'preview', 'lead', 'audience', 'months', 'body', 'cta', 'path', 'ctaNoGecko', 'pathNoGecko', 'visitorCta', 'visitorPath', 'visitors'];

/** The exact TypeScript text for these notes (already in step order). */
export function buildWeeklyNotesModule(notes) {
  const entries = notes.map((note) => {
    const lines = FIELDS.map((field) => `    ${field}: ${JSON.stringify(note[field] ?? null)},`);
    return ['  {', ...lines, '  },'].join('\n');
  });
  return [
    `// ${HEADER}`,
    '',
    'export type WeeklyNote = {',
    '  step: number;',
    '  slug: string;',
    '  subject: string;',
    '  // The line the inbox shows after the subject.',
    '  preview: string;',
    '  // Opening sentences from the member\'s record, tried in order; the',
    '  // first whose placeholders all fill is used. Empty: no lead.',
    '  lead: readonly string[];',
    '  // everyone, keepers, female, adult-female or breeders.',
    '  audience: string;',
    '  // The months (1 to 12, UTC) the note may go in; null: any month.',
    '  months: readonly number[] | null;',
    '  body: string;',
    '  cta: string;',
    '  path: string;',
    '  ctaNoGecko: string | null;',
    '  pathNoGecko: string | null;',
    '  // The button for a visitor without an account; null uses cta and path.',
    '  visitorCta: string | null;',
    '  visitorPath: string | null;',
    '  // false: members only (the note is about pages that need an account).',
    '  visitors: boolean;',
    '};',
    '',
    'export const WEEKLY_NOTES: readonly WeeklyNote[] = [',
    ...entries,
    '];',
    '',
  ].join('\n');
}

function main() {
  const notes = readWeeklyNotes();
  // New slugs join the published list first, so the checks see the list
  // as it will be written. A slug that vanished (a rename) still fails.
  const ledger = withNewSlugs(notes, readPublished());
  const problems = allProblems(notes, { ledger });
  if (problems.length) {
    console.error(`[weekly-notes] ${problems.length} problem(s); nothing written:\n${problems.map((p) => `  - ${p}`).join('\n')}`);
    process.exit(1);
  }
  writeFileSync(GENERATED_FILE, buildWeeklyNotesModule(notes));
  const text = publishedFileText(ledger);
  let before = null;
  try {
    before = readFileSync(PUBLISHED_FILE, 'utf8');
  } catch {
    // First build: the list is made now.
  }
  if (before !== text) writeFileSync(PUBLISHED_FILE, text);
  console.log(`[weekly-notes] wrote ${GENERATED_FILE_REL} from ${notes.length} notes in ${NOTES_DIR_REL}${before !== text ? ` and updated ${PUBLISHED_FILE_REL}` : ''}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) main();
